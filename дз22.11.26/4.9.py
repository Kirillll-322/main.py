#Известны две скорости: одна в километрах в час, другая — в метрах в секун-
#ду. Какая из скоростей больше?


kmh = float(input("Введите скорость в км/ч: "))
ms = float(input("Введите скорость в м/с: "))

kmh_in_ms= kmh / 3.6

if kmh_in_ms > ms:
    print(f"{kmh} км/ч будет больше чем {ms} м/с!")
elif kmh_in_ms < ms:
    print(f"{ms} м/с будет больше чем {kmh} км/ч ")
else:
    print(f"Скорости равны.")



